#!/bin/sh
# Runs from nginx's /docker-entrypoint.d before nginx starts (see Dockerfile.web).
#
# With RENKI_DAEMON_UPSTREAM set (host:port of the daemon, e.g. the Kubernetes
# Service `renki-daemon:4517`), proxies /api/* — REST and the WebSocket — to
# it, so the web app and daemon share one origin: no CORS, no daemon URL to
# type, and the browser's Setup screen finds it on its own. Unset (the
# docker-compose and plain static setups), nothing is added and the image
# behaves exactly as before.
#
# The proxy holds no secret: each browser still sends its own token.
set -eu

OUT_DIR=/etc/nginx/renki
OUT="$OUT_DIR/api-proxy.conf"
UPSTREAM="${RENKI_DAEMON_UPSTREAM:-}"

mkdir -p "$OUT_DIR"
rm -f "$OUT"

if [ -z "$UPSTREAM" ]; then
  echo "renki: RENKI_DAEMON_UPSTREAM not set, serving the web app only"
  exit 0
fi

# Interpolated into nginx config below — only a bare host[:port] is allowed, so
# a stray value can't inject directives. `case` matches the whole value, so an
# embedded newline can't sneak a second line past it (grep would check each
# line on its own).
case "$UPSTREAM" in
  *[!A-Za-z0-9.:-]* | :* | *: | *:*:*)
    echo "renki: RENKI_DAEMON_UPSTREAM must be host[:port], got: $UPSTREAM" >&2
    exit 1
    ;;
esac

cat >"$OUT" <<EOF
# Generated by 40-renki-api-proxy.sh from RENKI_DAEMON_UPSTREAM.
location /api/ {
  # Trailing slash strips the /api prefix: /api/ws -> /ws on the daemon.
  proxy_pass http://$UPSTREAM/;
  proxy_http_version 1.1;
  proxy_set_header Upgrade \$http_upgrade;
  proxy_set_header Connection \$connection_upgrade;
  proxy_set_header Host \$host;
  proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
  proxy_set_header X-Forwarded-Proto \$scheme;
  # The WebSocket stays open for as long as a tab does; streamed turns and
  # exports shouldn't sit in a buffer.
  proxy_read_timeout 1h;
  proxy_send_timeout 1h;
  proxy_buffering off;
  client_max_body_size 50m;
  # The WebSocket authenticates with ?token=, so log the path without its
  # query string rather than writing the token to stdout.
  access_log /var/log/nginx/access.log renki_noargs;
}
EOF

echo "renki: proxying /api/ to http://$UPSTREAM/"
